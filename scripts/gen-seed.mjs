// Generates the Lerato demo seed (TS module for tests + SQL rows for seed_demo) from scripts/lerato.csv,
// a verbatim copy of the Notion task "Zaka Demo: 10-week synthetic Lerato transaction history".
import { readFileSync, writeFileSync } from 'node:fs';

const END = '2026-10-15'; // last date in the CSV; seed_demo shifts it to "today"
const CAT = {
  opening_balance: ['opening_balance', 'cash', 'Opening cash balance'],
  taxi: ['transport', 'cash', 'Taxi return to work'],
  piece_job: ['piece_job', 'piece_job', 'Domestic work / piece job'],
  food: ['food', 'cash', 'Groceries / food'],
  electricity: ['electricity', 'cash', 'Prepaid electricity'],
  data_airtime: ['data_airtime', 'cash', 'Data / airtime bundle'],
  child_support_grant: ['grant', 'grant', 'Child Support Grant'],
  savings_goal: ['savings_goal', 'cash', 'Set aside for goal'],
  stokvel: ['stokvel', 'cash', 'Stokvel contribution'],
};
const day = (s) => Date.UTC(+s.slice(0, 4), +s.slice(5, 7) - 1, +s.slice(8, 10)) / 86400000;
const lines = readFileSync(new URL('./lerato.csv', import.meta.url), 'utf8').trim().split('\n').slice(1);
const rows = lines.map((l) => {
  const [id, date, direction, category, amount] = l.split(',');
  const [cat, source, note] = CAT[category];
  return { id: Number(id), offset: day(date) - day(END), direction, category: cat, source, cents: Number(amount) * 100, note };
});

writeFileSync(
  new URL('../src/data/lerato.ts', import.meta.url),
  `// GENERATED by scripts/gen-seed.mjs from scripts/lerato.csv — do not edit by hand.\n` +
    `// Synthetic demo data (Notion: "Zaka Demo: 10-week synthetic Lerato transaction history").\n` +
    `// offset = days before the last entry; stokvel rows are re-anchored by the seed (see seedLerato).\n` +
    `export const LERATO_END = '${END}';\n` +
    `export const LERATO_ROWS: [id: number, offset: number, direction: 'in' | 'out', category: string, source: string, cents: number, note: string][] = [\n` +
    rows.map((r) => `  [${r.id}, ${r.offset}, '${r.direction}', '${r.category}', '${r.source}', ${r.cents}, ${JSON.stringify(r.note)}],`).join('\n') +
    `\n];\n`,
);

const sqlRows = rows
  .map((r) => `      (${r.id}, ${r.offset}, '${r.direction}', '${r.category}', '${r.source}', ${r.cents}, '${r.note.replace(/'/g, "''")}')`)
  .join(',\n');
writeFileSync(new URL('./seed-rows.sql.txt', import.meta.url), sqlRows + '\n');
console.log(`${rows.length} rows`);
